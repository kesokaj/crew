package ingress

import (
	"fmt"
	"log/slog"
	"os"
	"sort"
	"strings"
)

// GeneratorConfig holds the environment-level configuration for Caddyfile generation.
type GeneratorConfig struct {
	BaseDomain        string   // e.g., "example.com" or "lab.example.com" — used for cookie domain
	AdminEmail        string   // ACME registration email
	SuperAdmins       []string // Platform superadmin emails (get superadmin role on ALL apps)
	DefaultRPS        int      // Default rate limit
	CaddyfileBasePath string   // Path to Caddyfile.base (optional)
	AuthDomain        string   // Absolute FQDN for auth portal (e.g., "auth.crew.example.com")
	AppsDomain        string   // Base for apps without an FQDN of their own (<hostname>.<AppsDomain>)
	IngressToken      string   // shared secret set as X-Crew-Ingress on Crew's own route alone (App.Sessions): proves ingress origin to the server
	JWTKey            string   // stable HMAC key so caddy-security JWTs survive restarts (else sessions break on redeploy)
	// AppsKey says the apps portal's key is in the ingress's environment (EnvAppsJWTKey): without
	// it no hosted route that needs a sign-in is served.
	AppsKey bool
	// Hosting says the ingress asks the server for hosted routes: an apps domain of its own and
	// Crew's key are there (plan M19 D23).
	Hosting bool
	// CloudflareDNS enables the `acme_dns cloudflare` global option, which
	// uses CLOUDFLARE_API_TOKEN for DNS-01 ACME challenges. When false
	// (no token), Caddy falls back to HTTP-01 challenges — sufficient for
	// non-wildcard hostnames, which is all the base app and auth portal need.
	// Wildcard certs require DNS-01 and will not issue without a token.
	CloudflareDNS bool
	// TLS is where certificates come from: TLSACME, TLSStaging, or TLSInternal.
	TLS string
	// AdminListen is the admin API's bind address. It is emitted into the
	// generated global options so the endpoint accepts requests only from
	// itself — see writeGlobalOptions.
	AdminListen string
}

// GenerateCaddyfile produces a complete Caddyfile from a list of discovered apps
// and the environment configuration. If a Caddyfile.base exists, its content is
// prepended to the generated output.
func GenerateCaddyfile(apps []App, cfg GeneratorConfig) string {
	var b strings.Builder

	// Prepend Caddyfile.base if it exists
	if cfg.CaddyfileBasePath != "" {
		baseContent, err := os.ReadFile(cfg.CaddyfileBasePath)
		if err != nil && !os.IsNotExist(err) {
			// Log non-trivial errors (permission denied, etc.) but continue
			slog.Warn("failed to read Caddyfile.base", "path", cfg.CaddyfileBasePath, "error", err)
		}
		if err == nil && len(baseContent) > 0 {
			b.WriteString("# ─── FROM Caddyfile.base (user-maintained) ───\n\n")
			b.Write(baseContent)
			b.WriteString("\n\n")
		}
	}

	b.WriteString("# ─── GENERATED by caddy-ingress (do not edit below) ───\n\n")

	// A hosted route that needs a sign-in is served only with the apps portal's key (plan M19 D6).
	apps = servable(apps, cfg)
	// Determine if any app needs OAuth (non-public)
	needsOAuth := false
	for _, app := range apps {
		if app.Mode != ModePublic {
			needsOAuth = true
			break
		}
	}

	// Global options block
	writeGlobalOptions(&b, apps, cfg, needsOAuth)

	// HTTP → HTTPS redirect
	b.WriteString("# HTTP → HTTPS (always)\nhttp:// {\n    redir https://{host}{uri} permanent\n}\n\n")

	// Auth portal (only if OAuth is needed)
	if needsOAuth {
		fmt.Fprintf(&b, "# Auth portal\n%s {\n    header Strict-Transport-Security \"max-age=31536000\"\n    authenticate with myportal\n}\n\n", cfg.AuthDomain)
	}
	if hostedSignIn(apps) {
		fmt.Fprintf(&b, "# The apps domain's portal\n%s {\n    header Strict-Transport-Security \"max-age=31536000\"\n    authenticate with appsportal\n}\n\n", appsAuthDomain(cfg))
	}

	// Sort apps by hostname for deterministic output
	sorted := make([]App, len(apps))
	copy(sorted, apps)
	sort.Slice(sorted, func(i, j int) bool {
		return sorted[i].Hostname < sorted[j].Hostname
	})

	// Per-app site blocks; with a DNS token the hosted projects share one wildcard site.
	wildcard := cfg.CloudflareDNS && cfg.TLS != TLSInternal
	var hosted []App
	for _, app := range sorted {
		if app.Hosted && wildcard {
			hosted = append(hosted, app)
			continue
		}
		writeAppBlock(&b, app, cfg)
	}
	if len(hosted) > 0 {
		writeWildcard(&b, hosted, cfg)
	}

	return b.String()
}

// servable leaves out a hosted route that needs a sign-in when the apps portal has no key.
func servable(apps []App, cfg GeneratorConfig) []App {
	out := make([]App, 0, len(apps))
	for _, app := range apps {
		if app.Hosted && app.Mode != ModePublic && !cfg.AppsKey {
			continue
		}
		out = append(out, app)
	}
	return out
}

// hostedSignIn says a hosted route needs the apps domain's portal.
func hostedSignIn(apps []App) bool {
	for _, app := range apps {
		if app.Hosted && app.Mode != ModePublic {
			return true
		}
	}
	return false
}

// appsAuthDomain is the apps domain's portal: the apps domain is another registered domain than
// Crew's (R172), so Crew's portal's cookie never reaches it.
func appsAuthDomain(cfg GeneratorConfig) string { return "auth." + cfg.AppsDomain }

// writeWildcard writes the hosted projects as one site of the apps domain's wildcard, whose
// certificate comes through the DNS provider: a handle for each project, and 404 for any other name.
func writeWildcard(b *strings.Builder, apps []App, cfg GeneratorConfig) {
	fmt.Fprintf(b, "# The hosted projects, one wildcard site\n*.%s {\n", cfg.AppsDomain)
	for _, app := range apps {
		name := sanitizePolicyName(app.Hostname)
		var body strings.Builder
		writeAppBody(&body, app, cfg)
		fmt.Fprintf(b, "    @%s_host host %s.%s\n    handle @%s_host {\n", name, app.Hostname, cfg.AppsDomain, name)
		for _, line := range strings.Split(strings.TrimSuffix(body.String(), "\n"), "\n") {
			b.WriteString("    " + line + "\n")
		}
		b.WriteString("    }\n")
	}
	b.WriteString("    handle {\n        respond 404\n    }\n}\n\n")
}

func writeGlobalOptions(b *strings.Builder, apps []App, cfg GeneratorConfig, needsOAuth bool) {
	b.WriteString("{\n")
	fmt.Fprintf(b, "    email %s\n", cfg.AdminEmail)
	switch cfg.TLS {
	case TLSInternal:
		b.WriteString("    local_certs\n")
	case TLSStaging:
		fmt.Fprintf(b, "    acme_ca %s\n", StagingCA)
	}
	if cfg.CloudflareDNS && cfg.TLS != TLSInternal {
		b.WriteString("    acme_dns cloudflare {env.CLOUDFLARE_API_TOKEN}\n")
	}
	b.WriteString("    auto_https disable_redirects\n\n")

	// The admin API reconfigures the ENTIRE ingress, the sign-in in front of
	// Crew included. The `admin <addr>` line is a REAL control: every /load REPLACES the admin
	// server per the loaded config, and a config that omits the block can move
	// the listener off loopback — observed live 2026-09-01, when a failed boot
	// load left the admin on 0.0.0.0:<random> with host checking disabled.
	// Emitting the loopback pin in every generated config forecloses that,
	// alongside the loadConfig loopback-bind guard and the >=2.11.4 Caddy
	// floor (GO-2026-4537 / GO-2026-5743). The `origins` line, by contrast, is
	// browser-only defense-in-depth: Caddy consults it solely when a request
	// carries an Origin/Sec-* header, so it does NOT gate a header-less local
	// `curl` and does not, on its own, make /load caller-bound.
	if cfg.AdminListen != "" {
		fmt.Fprintf(b, "    admin %s {\n        origins %s\n    }\n\n", cfg.AdminListen, cfg.AdminListen)
	}

	b.WriteString("    order rate_limit before basicauth\n")
	if needsOAuth {
		b.WriteString("    order authenticate before respond\n")
		b.WriteString("    order authorize before reverse_proxy\n")
	}
	b.WriteString("\n")

	// Prometheus metrics at admin API (:2019/metrics)
	b.WriteString("    metrics {\n")
	b.WriteString("        per_host\n")
	b.WriteString("    }\n")

	if needsOAuth {
		b.WriteString("\n")
		writeSecurityBlock(b, apps, cfg)
	}

	b.WriteString("}\n\n")
}

// SessionLifetimeSeconds is how long a sign-in lasts on a device: 30 days
// (design 20.3). It is the lifetime of the token the portal issues and of the
// cookie that holds it, which without one ends when the browser closes. The
// server shortens it with sessions.days, and refuses a signed-out device and a
// stale sign-in where 20.3 asks for a fresh one, from the two headers below.
// It is the one portal's, so hosted apps' sign-ins last as long.
const SessionLifetimeSeconds = 30 * 24 * 60 * 60

// writeSecurityBlock writes the caddy-security configuration including the
// OAuth identity provider, authentication portal with user transforms,
// and per-app authorization policies.
func writeSecurityBlock(b *strings.Builder, apps []App, cfg GeneratorConfig) {
	b.WriteString("    security {\n")

	// Identity provider
	b.WriteString("        oauth identity provider google {\n")
	b.WriteString("            realm google\n")
	b.WriteString("            driver google\n")
	b.WriteString("            client_id {env.GOOGLE_CLIENT_ID}\n")
	b.WriteString("            client_secret {env.GOOGLE_CLIENT_SECRET}\n")
	b.WriteString("            scopes openid email profile\n")
	b.WriteString("        }\n\n")

	// Authentication portal
	fmt.Fprintf(b, "        authentication portal myportal {\n")
	b.WriteString("            enable identity provider google\n")
	fmt.Fprintf(b, "            cookie domain %s\n", cfg.BaseDomain)
	// Lax: a cross-SITE WebSocket handshake or fetch does not carry the
	// session. The server also refuses cross-origin sockets before any side
	// effect; this closes the other half.
	fmt.Fprintf(b, "            cookie samesite lax\n")
	// The cookie that holds the token lasts as long as the token; without a
	// lifetime it would end when the browser closes.
	fmt.Fprintf(b, "            cookie lifetime %d\n", SessionLifetimeSeconds)
	// A per-deployment cookie name: see CookiePrefix.
	fmt.Fprintf(b, "            set cookie name prefix %s\n", CookiePrefix(cfg.BaseDomain))
	// Leading dot: go-authcrunch matches the redirect host with a bare
	// HasSuffix, so a bare domain would trust "evil<base>" as a post-login
	// redirect target, an open redirect on the portal. ".<base>" is
	// label-bounded; the app host <name>.<base> and the auth host auth.<base>
	// still match; the apex is not a served site.
	fmt.Fprintf(b, "            trust login redirect uri domain suffix .%s path prefix /\n", cfg.BaseDomain)
	// Crew's own address is the base domain itself, which the suffix rule
	// above does not match: it is trusted by its exact name.
	fmt.Fprintf(b, "            trust login redirect uri domain exact %s path prefix /\n", cfg.BaseDomain)
	// Sign in again on a signed-out device goes through the portal's logout,
	// which removes the session id the token's jti comes from, and back to
	// Crew's own address, which sends it to Google for a new sign-in. Only
	// Crew's address is trusted as the place to come back to.
	fmt.Fprintf(b, "            trust logout redirect uri domain exact %s path prefix /\n", cfg.BaseDomain)
	// Set deliberately instead of the plugin's 900 s default, which made a
	// page reload every quarter hour. The lifetime is not how a device is
	// signed out: the server refuses a signed-out device's token at once
	// (design 20.3); the lifetime bounds how long a token Crew never saw stays
	// valid.
	fmt.Fprintf(b, "            crypto default token lifetime %d\n", SessionLifetimeSeconds)
	if cfg.JWTKey != "" {
		// Pin the token signing key so sessions survive a Caddy restart and
		// the portal + authorizers always agree (auto-generated keys reset).
		b.WriteString("            crypto key sign-verify {env.CREW_JWT_KEY}\n")
	}

	// Write user transforms for role-gated apps
	for _, app := range apps {
		if app.Mode != ModeRoleGated || app.Hosted {
			continue
		}

		// Platform superadmins get superadmin role on ALL apps
		for _, email := range cfg.SuperAdmins {
			if !containsEmail(app.SuperAdmins, email) {
				writeTransform(b, email, fmt.Sprintf("app/%s/superadmin", app.Hostname))
			}
		}
		// Per-app superadmins (highest privilege)
		for _, email := range app.SuperAdmins {
			writeTransform(b, email, fmt.Sprintf("app/%s/superadmin", app.Hostname))
		}
		// Per-app admins
		for _, email := range app.Admins {
			writeTransform(b, email, fmt.Sprintf("app/%s/admin", app.Hostname))
		}
		// Per-app viewers
		for _, email := range app.Viewers {
			writeTransform(b, email, fmt.Sprintf("app/%s/viewer", app.Hostname))
		}
	}

	// For mode 2 (authenticated) apps, superadmins + default admins get roles
	for _, app := range apps {
		if app.Mode != ModeAuthenticated || app.Hosted {
			continue
		}
		for _, email := range cfg.SuperAdmins {
			writeTransform(b, email, fmt.Sprintf("app/%s/superadmin", app.Hostname))
		}
	}

	b.WriteString("        }\n\n")
	if hostedSignIn(apps) {
		writeAppsPortal(b, cfg)
	}

	// Authorization policies (one per non-public app)
	for _, app := range apps {
		if app.Mode == ModePublic {
			continue
		}
		writeAuthzPolicy(b, app, cfg)
	}

	b.WriteString("    }\n")
}

// writeAppsPortal writes the apps domain's own portal (19.4, R172, plan M19 D6): its cookie is for
// the apps domain, under its own prefix, signed with its own key, so a token of one domain is no
// token on the other. It adds no role: a hosted route allows by mail address in its policy (D38).
func writeAppsPortal(b *strings.Builder, cfg GeneratorConfig) {
	b.WriteString("        authentication portal appsportal {\n")
	b.WriteString("            enable identity provider google\n")
	fmt.Fprintf(b, "            cookie domain %s\n", cfg.AppsDomain)
	b.WriteString("            cookie samesite lax\n")
	fmt.Fprintf(b, "            cookie lifetime %d\n", SessionLifetimeSeconds)
	fmt.Fprintf(b, "            set cookie name prefix %s\n", CookiePrefix(cfg.AppsDomain))
	// Label-bounded, as Crew's portal's: <project>.<apps domain> and the portal itself.
	fmt.Fprintf(b, "            trust login redirect uri domain suffix .%s path prefix /\n", cfg.AppsDomain)
	fmt.Fprintf(b, "            crypto default token lifetime %d\n", SessionLifetimeSeconds)
	fmt.Fprintf(b, "            crypto key sign-verify {env.%s}\n", EnvAppsJWTKey)
	b.WriteString("        }\n\n")
}

// writeTransform writes a single transform user block.
func writeTransform(b *strings.Builder, email, role string) {
	b.WriteString("            transform user {\n")
	fmt.Fprintf(b, "                match email %s\n", email)
	fmt.Fprintf(b, "                action add role %s\n", role)
	b.WriteString("            }\n")
}

// writeAuthzPolicy writes an authorization policy for a single app.
func writeAuthzPolicy(b *strings.Builder, app App, cfg GeneratorConfig) {
	policyName := sanitizePolicyName(app.Hostname)
	fmt.Fprintf(b, "        authorization policy %s_policy {\n", policyName)
	if app.Hosted {
		writeHostedPolicy(b, app, cfg)
		return
	}
	// Point directly to Google OAuth to skip the portal login page
	fmt.Fprintf(b, "            set auth url https://%s/oauth2/google/\n", cfg.AuthDomain)
	// Read this deployment's session cookie: the policy's default list names
	// only the plugin's default, which the portal does not write.
	fmt.Fprintf(b, "            set access_token cookie name %s\n", AuthCookieName(cfg.BaseDomain))
	if cfg.JWTKey != "" {
		b.WriteString("            crypto key verify {env.CREW_JWT_KEY}\n")
	}

	switch app.Mode {
	case ModeAuthenticated:
		// Any authenticated user can access (authp/user for known domains, authp/guest for others)
		// If superadmins or default admins exist, include their roles in the access list too
		var roles []string
		if len(cfg.SuperAdmins) > 0 {
			roles = append(roles, fmt.Sprintf("app/%s/superadmin", app.Hostname))
		}
		roles = append(roles, "authp/user", "authp/guest")
		fmt.Fprintf(b, "            allow roles %s\n", strings.Join(roles, " "))
	case ModeRoleGated:
		// Only specific roles can access
		var roles []string
		if len(app.SuperAdmins) > 0 || len(cfg.SuperAdmins) > 0 {
			roles = append(roles, fmt.Sprintf("app/%s/superadmin", app.Hostname))
		}
		roles = append(roles, fmt.Sprintf("app/%s/admin", app.Hostname))
		if len(app.Viewers) > 0 {
			roles = append(roles, fmt.Sprintf("app/%s/viewer", app.Hostname))
		}
		fmt.Fprintf(b, "            allow roles %s\n", strings.Join(roles, " "))
	}

	b.WriteString("            inject headers with claims\n")
	if app.Sessions {
		// The sign-in's time and the device's id, for the server's sessions
		// (design 20.3). The plugin sets a header only when the claim is
		// there, so the route strips the client's copies first.
		fmt.Fprintf(b, "            inject header %q from iat\n", HeaderAuthTime)
		fmt.Fprintf(b, "            inject header %q from jti\n", HeaderSession)
	}
	fmt.Fprintf(b, "        }\n\n")
}

// writeHostedPolicy writes a hosted route's policy: the apps portal's sign-in, cookie and key, and who
// may open it by mail address, or any Google account (plan M19 D38). It passes no session header.
func writeHostedPolicy(b *strings.Builder, app App, cfg GeneratorConfig) {
	fmt.Fprintf(b, "            set auth url https://%s/oauth2/google/\n", appsAuthDomain(cfg))
	fmt.Fprintf(b, "            set access_token cookie name %s\n", AuthCookieName(cfg.AppsDomain))
	fmt.Fprintf(b, "            crypto key verify {env.%s}\n", EnvAppsJWTKey)
	if app.Mode == ModeRoleGated {
		fmt.Fprintf(b, "            allow email %s\n", strings.Join(app.Emails, " "))
	} else {
		b.WriteString("            allow roles authp/user authp/guest\n")
	}
	b.WriteString("            inject headers with claims\n")
	b.WriteString("        }\n\n")
}

// writeAppBlock writes a single site block for an app.
func writeAppBlock(b *strings.Builder, app App, cfg GeneratorConfig) {
	// A route with a full name of its own, as Crew's server has, is served at
	// that name; any other at <hostname>.<AppsDomain>.
	fqdn := app.FQDN
	if fqdn == "" {
		fqdn = fmt.Sprintf("%s.%s", app.Hostname, cfg.AppsDomain)
	}

	// Comment with mode
	modeStr := "public"
	if app.Mode == ModeAuthenticated {
		modeStr = "authenticated"
	} else if app.Mode == ModeRoleGated {
		modeStr = "role-gated"
	}
	fmt.Fprintf(b, "# %s (%s, %d rps)\n", app.Hostname, modeStr, app.RPS)

	fmt.Fprintf(b, "%s {\n", fqdn)
	writeAppBody(b, app, cfg)
	b.WriteString("}\n\n")
}

// writeAppBody writes what a site does for an app: its own site's, or a handle of the wildcard's.
func writeAppBody(b *strings.Builder, app App, cfg GeneratorConfig) {
	// HTTPS only, for a year: a browser never tries plain HTTP on this site again.
	b.WriteString("    header Strict-Transport-Security \"max-age=31536000\"\n")

	// Rate limiting
	fmt.Fprintf(b, "    rate_limit {\n")
	fmt.Fprintf(b, "        zone %s_rl {\n", sanitizePolicyName(app.Hostname))
	fmt.Fprintf(b, "            key {remote_host}\n")
	fmt.Fprintf(b, "            events %d\n", app.RPS)
	fmt.Fprintf(b, "            window 1s\n")
	fmt.Fprintf(b, "        }\n")
	fmt.Fprintf(b, "    }\n")

	if app.Mode == ModePublic {
		// Public + unauthenticated: strip any client-supplied identity / ingress
		// headers before proxying so they can't be forwarded upstream and spoof
		// anything downstream (a public app carries no identity), then set the
		// authentic public role.
		for _, h := range clientHeaders {
			fmt.Fprintf(b, "    request_header -%s\n", h)
		}
		// A public app is someone's container on the base domain, where the
		// portal's session cookies are sent too: cut them out before proxying,
		// or the app could replay the operator's session.
		fmt.Fprintf(b, "    request_header Cookie \"%s\" \"\"\n", PortalCookieStrip)
		fmt.Fprintf(b, "    request_header %s \"%s\"\n", HeaderRole, RolePublic)
		writeProxy(b, app, "    ")
	} else {
		policyName := sanitizePolicyName(app.Hostname)
		// The ingress's door on the server is the ingress's alone: through Crew's route it is not
		// found, signed in or not (plan M19 D5).
		if app.Sessions {
			fmt.Fprintf(b, "    @%s_door path /ingress /ingress/*\n", policyName)
			fmt.Fprintf(b, "    handle @%s_door {\n        respond 404\n    }\n", policyName)
		}
		// Every hosted project is the same site under the apps domain, with one sign-in: a change asked
		// by another site, such as another hosted project's page, is refused before the sign-in is read,
		// so one project cannot make the operator's browser change another (security review of M19). So
		// is a WebSocket asked by another site, which is a GET that stays open; and a browser that sends
		// no Sec-Fetch-Site is refused a change whose Origin is another (round 2). A public project has
		// no sign-in to ride, and takes whatever other sites send it.
		if app.Hosted {
			own := "https://" + app.Hostname + "." + cfg.AppsDomain
			fmt.Fprintf(b, "    @%s_xsite {\n        not method GET HEAD OPTIONS\n        header_regexp Sec-Fetch-Site ^(same-site|cross-site)$\n    }\n", policyName)
			fmt.Fprintf(b, "    handle @%s_xsite {\n        respond 403\n    }\n", policyName)
			fmt.Fprintf(b, "    @%s_xws {\n        header Upgrade websocket\n        header_regexp Sec-Fetch-Site ^(same-site|cross-site)$\n    }\n", policyName)
			fmt.Fprintf(b, "    handle @%s_xws {\n        respond 403\n    }\n", policyName)
			fmt.Fprintf(b, "    @%s_xorigin {\n        not method GET HEAD OPTIONS\n        header !Sec-Fetch-Site\n        header Origin *\n        not header Origin %s\n    }\n", policyName, own)
			fmt.Fprintf(b, "    handle @%s_xorigin {\n        respond 403\n    }\n", policyName)
			// A browser sends Origin on every WebSocket handshake, also one that sends no Sec-Fetch-Site:
			// one from another Origin is refused whatever Sec-Fetch-Site says (security review of the
			// release of M20).
			fmt.Fprintf(b, "    @%s_xwsorigin {\n        header Upgrade websocket\n        header Origin *\n        not header Origin %s\n    }\n", policyName, own)
			fmt.Fprintf(b, "    handle @%s_xwsorigin {\n        respond 403\n    }\n", policyName)
		}
		// The open paths first, without the sign-in and without any identity
		// or ingress header, so that nothing they receive vouches for a user.
		if len(app.OpenPaths) > 0 {
			fmt.Fprintf(b, "    @%s_open path %s\n", policyName, strings.Join(app.OpenPaths, " "))
			fmt.Fprintf(b, "    handle @%s_open {\n", policyName)
			for _, h := range append(clientHeaders[:len(clientHeaders):len(clientHeaders)],
				UpstreamHeaderEmail, UpstreamHeaderName, UpstreamHeaderRoles, UpstreamHeaderSub) {
				fmt.Fprintf(b, "        request_header -%s\n", h)
			}
			fmt.Fprintf(b, "        request_header Cookie \"%s\" \"\"\n", PortalCookieStrip)
			fmt.Fprintf(b, "        reverse_proxy %s:%d\n", app.ContainerIP, app.Port)
			b.WriteString("    }\n")
		}
		// Use route{} for explicit handler ordering:
		// authorize → set clean headers → strip upstream headers → reverse_proxy
		b.WriteString("    handle {\n")
		b.WriteString("    route {\n")
		// Defense in depth: strip any CLIENT-supplied copies of the upstream
		// claim headers BEFORE the authorizer injects the authentic ones, so a
		// spoofed X-Token-User-Email can never win the placeholder below (guards
		// against caddy-security using Header.Add rather than Set).
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderEmail)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderName)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderRoles)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderSub)
		// The session headers are the authorizer's to set, on Crew's route
		// only; a client's copy never passes, on any route.
		fmt.Fprintf(b, "        request_header -%s\n", HeaderAuthTime)
		fmt.Fprintf(b, "        request_header -%s\n", HeaderSession)
		fmt.Fprintf(b, "        authorize with %s_policy\n", policyName)

		// Set clean identity headers from caddy-security's injected upstream headers
		fmt.Fprintf(b, "        request_header %s \"{http.request.header.%s}\"\n", HeaderEmail, UpstreamHeaderEmail)
		fmt.Fprintf(b, "        request_header %s \"{http.request.header.%s}\"\n", HeaderUser, UpstreamHeaderName)
		fmt.Fprintf(b, "        request_header %s \"{http.request.header.%s}\"\n", HeaderSubject, UpstreamHeaderSub)

		if app.Mode == ModeRoleGated && app.Hosted {
			// A hosted project is told who signed in, as the user it allowed (D38).
			fmt.Fprintf(b, "        request_header %s \"%s\"\n", HeaderRole, RoleUser)
		} else if app.Mode == ModeRoleGated {
			// Strip any CLIENT-supplied role first. Unlike the identity headers
			// above, the role is set only INSIDE the matchers below, so a
			// request matching none of them would otherwise carry the client's
			// own X-Caddy-Role straight to the upstream. Nothing reads that
			// header today, which is exactly why this is cheap to fix now and
			// would look like an authorization bug the day something does.
			// Authenticated mode sets the header
			// unconditionally in the else branch, so it needs no strip.
			fmt.Fprintf(b, "        request_header -%s\n", HeaderRole)
			// Set role: viewer first, then admin, then superadmin overwrites (highest wins)
			fmt.Fprintf(b, "        @%s_viewer header_regexp %s \"app/%s/%s\"\n", policyName, UpstreamHeaderRoles, app.Hostname, RoleViewer)
			fmt.Fprintf(b, "        request_header @%s_viewer %s \"%s\"\n", policyName, HeaderRole, RoleViewer)
			fmt.Fprintf(b, "        @%s_admin header_regexp %s \"app/%s/%s\"\n", policyName, UpstreamHeaderRoles, app.Hostname, RoleAdmin)
			fmt.Fprintf(b, "        request_header @%s_admin %s \"%s\"\n", policyName, HeaderRole, RoleAdmin)
			fmt.Fprintf(b, "        @%s_superadmin header_regexp %s \"app/%s/%s\"\n", policyName, UpstreamHeaderRoles, app.Hostname, RoleSuperAdmin)
			fmt.Fprintf(b, "        request_header @%s_superadmin %s \"%s\"\n", policyName, HeaderRole, RoleSuperAdmin)
		} else {
			// Authenticated mode: any Google user gets role "user"
			fmt.Fprintf(b, "        request_header %s \"%s\"\n", HeaderRole, RoleUser)
		}

		// Strip caddy-security internal headers
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderEmail)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderName)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderRoles)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderSub)

		// The portal's cookies are sent to every host under the base domain, and
		// the token in them lasts 30 days: once the authorizer has read them, no
		// upstream gets them, so an app cannot replay the operator's sign-in
		// against Crew (security review of M17 P4). The upstream knows who it is
		// from the headers above; its own cookies pass.
		fmt.Fprintf(b, "        request_header Cookie \"%s\" \"\"\n", PortalCookieStrip)

		// Ingress origin proof: strip any client-supplied token, then set the
		// shared one so the upstream can reject requests that reach it
		// directly (e.g. a container on a shared bridge spoofing X-Caddy-Email).
		// The strip is unconditional so a token-less deploy still can't relay
		// a forged header. The token goes to Crew's own route alone: with it
		// the server takes the admin's mail and the time of a sign-in, so an
		// app that got it could call Crew's API as a fresh operator (security
		// review of M17's Close).
		fmt.Fprintf(b, "        request_header -%s\n", HeaderIngress)
		if cfg.IngressToken != "" && app.Sessions {
			fmt.Fprintf(b, "        request_header %s %q\n", HeaderIngress, cfg.IngressToken)
		}

		writeProxy(b, app, "        ")
		b.WriteString("    }\n")
		b.WriteString("    }\n")
	}
}

// writeProxy writes the reverse proxy to an app. A hosted app's Set-Cookie loses its Domain, so the
// cookie a response sets is its own host's (plan M19 D26); a page's script can still set a cookie for
// the apps domain, which design 19.4 records.
func writeProxy(b *strings.Builder, app App, ind string) {
	if !app.Hosted {
		fmt.Fprintf(b, "%sreverse_proxy %s:%d\n", ind, app.ContainerIP, app.Port)
		return
	}
	fmt.Fprintf(b, "%sreverse_proxy %s:%d {\n", ind, app.ContainerIP, app.Port)
	fmt.Fprintf(b, "%s    header_down Set-Cookie \"(?i);\\s*domain=[^;]*\" \"\"\n", ind)
	fmt.Fprintf(b, "%s}\n", ind)
}

// sanitizePolicyName converts a hostname into a valid Caddy policy name.
// Replaces hyphens and dots with underscores.
func sanitizePolicyName(hostname string) string {
	s := strings.ReplaceAll(hostname, "-", "_")
	s = strings.ReplaceAll(s, ".", "_")
	return s
}

// containsEmail checks if an email exists in a slice.
func containsEmail(emails []string, target string) bool {
	for _, e := range emails {
		if strings.EqualFold(e, target) {
			return true
		}
	}
	return false
}
